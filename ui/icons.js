const seen = new Set();
export function renderIcon(id, { size = 18 } = {}) {
  const paths = ICONS[id];
  if (!paths) {
    if (!seen.has(id)) { seen.add(id); console.error(`renderIcon: no icon for id "${id}"`); }
    return '';
  }
  const body = paths.map((d) => `<path d="${d}"/>`).join('');
  return `<svg class="ui-icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function iconIds() {
  return Object.keys(ICONS);
}
